#!/usr/bin/env python3
"""Generate the Unicode 16 letter/number ranges used by Qwen2 tokenization."""
import argparse
import hashlib
from pathlib import Path
import urllib.request

URL = "https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt"
SHA256 = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, help="use a local UnicodeData.txt")
    args = parser.parse_args()
    data = args.data.read_bytes() if args.data else urllib.request.urlopen(URL).read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("UnicodeData.txt hash mismatch")
    flags = bytearray(0x110000)
    start = 0
    for line in data.decode().splitlines():
        code, name, category, *_ = line.split(";")
        end = int(code, 16)
        value = {"L": 1, "N": 2}.get(category[0], 0)
        if name.endswith(", First>"):
            start = end
            continue
        begin = start if name.endswith(", Last>") else end
        flags[begin:end + 1] = bytes([value]) * (end - begin + 1)
    rows = []
    begin = 0
    for end in range(1, len(flags) + 1):
        if end == len(flags) or flags[end] != flags[begin]:
            if flags[begin]:
                rows.append(f"  {{0x{begin:x}, 0x{end - 1:x}, {flags[begin]}}},")
            begin = end
    output = Path(__file__).resolve().parents[1] / "src/unicode_ranges.inc"
    output.write_text("// Generated by scripts/generate_unicode.py from Unicode 16.0.0.\n"
                      "// Unicode data license: https://www.unicode.org/license.txt\n" +
                      "\n".join(rows) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
